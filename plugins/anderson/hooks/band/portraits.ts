// Who sits in each stage when no live seat has a portrait of its own.
const STAGE_FACE: Record<string, string> = {
  plan: 'THE ARCHITECT', plan_review: 'THE ORACLE', implement: 'NEO', repair: 'TRINITY', diff_review: 'AGENT SMITH', done: 'NEO',
}

/** The portrait to show: the newest live seat that has one, else the stage's persona, else none. */
export function portraitFor(seats: Seat[], pipe: Pipe | null): string | undefined {
  const live = seats.filter(s => s.doneAt === undefined && SPRITES[s.name]).sort((a, b) => b.startedAt - a.startedAt)
  return live[0]?.name ?? (pipe ? STAGE_FACE[pipe.stage] : undefined)
}

type Px = (number | undefined)[][] // 0xRRGGBB, or undefined for transparent; alpha in the top byte when set
const rnd = (s: number) => { const x = Math.sin(s * 12.9898) * 43758.5453; return x - Math.floor(x) }
const a = (rgb: number, alpha: number) => (Math.round(alpha * 255) << 24 >>> 0) + rgb

// Per-persona movement, a function of the tick alone (250 ms per tick).
const FX: Record<string, (px: Px, t: number) => void> = {
  // Glint sweeps across both lenses every 8 s.
  NEO: (px, t) => {
    const s = (t % 32) - 4
    for (const y of [8, 9]) for (const x of [s + 9 - y, s + 14 - y]) if ((x >= 8 && x <= 10) || (x >= 13 && x <= 15)) px[y]![x] = 0xeaffea
  },
  // Earpiece blinks; every 8 s the face glitches into a shifted copy.
  'AGENT SMITH': (px, t) => {
    if (t % 8 < 4) for (let y = 9; y <= 16; y++) if (px[y]![19] !== undefined) px[y]![19] = 0x3cff7a
    if (t % 32 < 2) for (const row of px) for (let x = SIZE - 1; x >= 2; x--) if (row[x] === undefined && row[x - 2] !== undefined) row[x] = 0x1f7a45
  },
  // Reflections slide left and right: looking around.
  TRINITY: (px, t) => {
    const o = Math.round(Math.sin(t / 5))
    px[9]![9] = PAL.G; px[9]![14] = PAL.G
    px[9]![9 + o] = PAL.g; px[9]![14 + o] = PAL.g
  },
  // Cigarette at the mouth corner, the ember breathes, smoke curls up.
  'THE ORACLE': (px, t) => {
    for (let x = 14; x <= 17; x++) px[13]![x] = 0xeeeeee
    px[13]![18] = t % 6 < 3 ? 0xff8a3c : 0xa8401a
    for (let i = 0; i < 4; i++) {
      const y = 12 - Math.floor((t * 0.5 + i * 3) % 12)
      const x = 18 + Math.round(1.3 * Math.sin((t + i * 5) / 3 + y / 2))
      if (y >= 0 && x < SIZE && px[y]![x] === undefined) px[y]![x] = a(0xbec8c3, 0.25 + y / 24)
    }
  },
  // Code flickers in his lenses: his wall of monitors.
  'THE ARCHITECT': (px, t) => {
    for (const x of [8, 9, 14, 15]) px[9]![x] = [0x3cff7a, 0x1f7a45, 0x0e3d22, 0x7dffb0][Math.floor(rnd(x * 13 + t) * 4)]
  },
}

/** Matrix rain through the transparent background, stateless: each column's drop is placed by the tick. */
function rain(px: Px, t: number) {
  for (let x = 0; x < SIZE; x++) {
    const speed = 0.3 + rnd(x * 7) * 0.5, period = SIZE + 14
    const head = Math.floor((t * speed + rnd(x) * period) % period) - 7
    for (let dy = 0; dy < 7; dy++) {
      const y = head - dy
      if (y >= 0 && y < SIZE && px[y]![x] === undefined) px[y]![x] = dy === 0 ? 0x7dffb0 : a(0x3cff7a, 0.45 - dy * 0.06)
    }
  }
}

/** One frame of a persona's portrait as RGBA bytes (SIZE x SIZE). */
export function frame(who: string, t: number): Uint8Array {
  const px: Px = (SPRITES[who] ?? []).map(r => [...r].map(ch => PAL[ch]))
  rain(px, t)
  FX[who]?.(px, t)
  const out = new Uint8Array(SIZE * SIZE * 4)
  px.forEach((row, y) => row.forEach((c, x) => {
    if (c === undefined) return
    const i = (y * SIZE + x) * 4
    out[i] = (c >> 16) & 255; out[i + 1] = (c >> 8) & 255; out[i + 2] = c & 255
    out[i + 3] = c > 0xffffff ? c >>> 24 : 255
  }))
  return out
}
